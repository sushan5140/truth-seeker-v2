import re
from dataclasses import dataclass

from app.services.truth.domain import ClaimEvidenceMatrix, Evidence
from app.services.truth.evidence_processing import canonicalize_url
from app.services.truth.security import UnsafeUrlError
from app.services.truth.verdict_generation import VERDICT_NOTES


_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+")
_WORD_RE = re.compile(r"[a-z0-9]+")
_URL_RE = re.compile(r"https?://\S+")

# How much of a non-meta sentence's vocabulary must appear in the claim's
# retrieved evidence for it to count as evidence-grounded rather than
# fabricated. Same order of magnitude as Phase 5's claim-vs-evidence
# overlap threshold (0.25); calibrated slightly higher here because this
# checks whether a sentence was actually drawn from evidence, not just
# topically related to it.
MIN_GROUNDING_OVERLAP = 0.3

_ROUND_SUMMARY_RE = re.compile(r"^\d+ supporting and \d+ contradicting source\(s\) were found across \d+ retrieval round\(s\)\.$")
_UNRESOLVED_PREFIX = "Unresolved: "

NO_VALIDATED_CONTENT_NOTE = (
    "No portion of the generated explanation could be validated against the retrieved evidence; "
    "only the deterministic summary above reflects verified information."
)


def _words(text: str) -> set[str]:
    return set(_WORD_RE.findall(text.lower()))


def _is_meta_sentence(sentence: str) -> bool:
    """System-authored process commentary (evidence counts, round counts,
    gap listings, fixed verdict-type notes from verdict_generation.py) is
    never a factual assertion about the claim, so it's exempt from
    evidence-grounding checks by construction -- these strings are
    generated by our own code, not claimed as fact by a verifier, so they
    can't be a fabricated citation."""
    if sentence in VERDICT_NOTES.values():
        return True
    if sentence.startswith(_UNRESOLVED_PREFIX):
        return True
    return bool(_ROUND_SUMMARY_RE.match(sentence))


def _extract_urls(sentence: str) -> list[str]:
    return [match.rstrip(".,;:)]}") for match in _URL_RE.findall(sentence)]


def _url_is_grounded(url: str, evidence_urls: set[str]) -> bool:
    try:
        canonical = canonicalize_url(url)
    except (UnsafeUrlError, ValueError):
        return False
    return canonical in evidence_urls


def _evidence_vocabulary(evidence_items: list[Evidence]) -> set[str]:
    vocabulary: set[str] = set()
    for item in evidence_items:
        vocabulary |= _words(item.evidence_chunk)
    return vocabulary


def _evidence_url_set(evidence_items: list[Evidence]) -> set[str]:
    urls: set[str] = set()
    for item in evidence_items:
        for raw in (item.url, item.canonical_url):
            try:
                urls.add(canonicalize_url(raw))
            except (UnsafeUrlError, ValueError):
                continue
    return urls


@dataclass(frozen=True)
class CitationValidationResult:
    rationale: str
    original_sentence_count: int
    retained_sentence_count: int
    stripped_unsupported_count: int
    stripped_fabricated_url_count: int


def validate_rationale(rationale: str, matrix: ClaimEvidenceMatrix) -> CitationValidationResult:
    """Handoff doc section 7/18 invariant: every factual explanation must
    map back to retrieved evidence. Sentences that don't are stripped
    silently -- no inline marker is left in their place, matching the
    instruction that this corrects the explanation rather than annotating
    it. Sentences containing a URL that doesn't canonicalize to a real
    retrieved evidence URL are stripped as a fabricated citation
    regardless of how well their prose overlaps with evidence. If nothing
    evidence-grounded survives (only system-authored process commentary,
    or truly nothing), that's reported explicitly via
    NO_VALIDATED_CONTENT_NOTE rather than returning a thin or empty
    string.
    """
    sentences = [part.strip() for part in _SENTENCE_SPLIT_RE.split(rationale.strip()) if part.strip()]
    all_evidence = matrix.supporting + matrix.contradicting + matrix.context
    evidence_vocabulary = _evidence_vocabulary(all_evidence)
    evidence_urls = _evidence_url_set(all_evidence)

    retained: list[str] = []
    meta_retained = 0
    stripped_unsupported = 0
    stripped_fabricated_url = 0

    for sentence in sentences:
        if _is_meta_sentence(sentence):
            retained.append(sentence)
            meta_retained += 1
            continue

        urls = _extract_urls(sentence)
        if urls and not all(_url_is_grounded(url, evidence_urls) for url in urls):
            stripped_fabricated_url += 1
            continue

        sentence_words = _words(sentence)
        overlap = (len(sentence_words & evidence_vocabulary) / len(sentence_words)) if sentence_words else 0.0
        if overlap >= MIN_GROUNDING_OVERLAP:
            retained.append(sentence)
        else:
            stripped_unsupported += 1

    # Only flag "near-nothing meaningful" when something was actually
    # stripped. An all-meta rationale that never had non-meta content to
    # begin with (the heuristic's normal output whenever it has no
    # evidence-specific prose to add) isn't a validation failure -- it's
    # an honest summary, and appending this note there would falsely
    # imply content was lost.
    meaningful_retained = len(retained) - meta_retained
    anything_stripped = stripped_unsupported > 0 or stripped_fabricated_url > 0
    # Also covers a genuinely empty/unparseable input rationale (no
    # sentences at all) -- that must not silently become "" either.
    if meaningful_retained <= 0 and (anything_stripped or not sentences):
        retained.append(NO_VALIDATED_CONTENT_NOTE)

    return CitationValidationResult(
        rationale=" ".join(retained),
        original_sentence_count=len(sentences),
        retained_sentence_count=len(retained),
        stripped_unsupported_count=stripped_unsupported,
        stripped_fabricated_url_count=stripped_fabricated_url,
    )
